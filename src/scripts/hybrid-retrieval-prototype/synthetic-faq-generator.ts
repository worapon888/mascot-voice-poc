/**
 * Builds a dataset of synthetic FAQs with realistic public service topics.
 * Guarantees that FAQ IDs 1..5 are always the real baseline demo FAQs.
 */
export function generateSyntheticFaqDataset(
  targetCount: 100 | 300 | 600,
): FaqRecord[] {
  const result: FaqRecord[] = [...REAL_SEEDED_FAQS];
  let currentId = 6;

  // Flatten domain templates
  const allTemplates: Array<{
    q: string;
    a: string;
    kw: string[];
    domain: string;
  }> = [];
  for (const d of SYNTHETIC_DOMAINS) {
    for (const item of d.items) {
      allTemplates.push({ ...item, domain: d.domain });
    }
  }

  // Multiply variations until target count is reached
  let round = 1;
  while (result.length < targetCount) {
    for (const t of allTemplates) {
      if (result.length >= targetCount) break;

      const suffix = round === 1 ? '' : ` (แบบที่ ${round})`;
      const q = `${t.q}${suffix}`;
      const a = `${t.a} (ข้อมูลสำหรับการประเมิน Synthetic Dataset #${currentId})`;
      const kw = [...t.kw, t.domain, `หัวข้อที่${currentId}`];

      result.push({
        id: currentId++,
        question: q,
        answer: a,
        keywords: kw,
        is_active: true,
        created_at: new Date(
          Date.now() - (targetCount - result.length) * 3600000,
        ).toISOString(),
      });
    }
    round++;
  }

  return result;
}
